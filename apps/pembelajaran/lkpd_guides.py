def get_lkpd_guide_for_module(slug, module_title=""):
    """
    Mengambil panduan & prompt LKPD spesifik modul.
    """
    if slug in MODULE_LKPD_GUIDES:
        return MODULE_LKPD_GUIDES[slug]
    
    clean_title = module_title or "Modul Pembelajaran"
    return {
        'prompt': f'1. Ringkasan Temuan & Laporan Analisis Tugas "{clean_title}":',
        'placeholder': f'Tuliskan temuan analisis, hasil eksplorasi, atau ringkasan tugas sesuai petunjuk modul "{clean_title}" (wajib diketik sendiri secara mandiri)...',
        'tip': '💡 Petunjuk: Jawab dengan jujur dan orisinal untuk mengasah pemahaman konsep.'
    }
